"""Inference helpers for the experimental BP-associated category classifier."""

from __future__ import annotations

from dataclasses import dataclass
import json
from pathlib import Path
from numbers import Real
from typing import Mapping

import numpy as np
import pandas as pd
import joblib

try:
    from train_selected_model import FEATURE_COLUMNS, LABEL_MAPPING, MODEL_PATH, METADATA_PATH
except ModuleNotFoundError:
    from .train_selected_model import FEATURE_COLUMNS, LABEL_MAPPING, MODEL_PATH, METADATA_PATH


_CATEGORY_BY_ID = {class_id: category for category, class_id in LABEL_MAPPING.items()}
_MODEL = None


@dataclass(frozen=True)
class BPCategoryPrediction:
    """Experimental BP-associated classification result."""

    predicted_class_id: int
    predicted_category: str
    probabilities: dict[str, float]
    experimental_result: str = (
        "Experimental BP-associated category estimate from daily dietary and personal features; "
        "not a diagnosis, a meal-suitability label, or a prediction of future blood pressure."
    )
    explanations: list[dict[str, object]] | None = None


def _load_model():
    global _MODEL
    if _MODEL is None:
        if not MODEL_PATH.exists():
            raise FileNotFoundError(f"Saved model not found: {MODEL_PATH}")
        _MODEL = joblib.load(MODEL_PATH)
    return _MODEL


def _features_to_frame(features: Mapping[str, Real]) -> pd.DataFrame:
    missing = [column for column in FEATURE_COLUMNS if column not in features]
    if missing:
        raise ValueError(f"Missing required feature(s): {', '.join(missing)}")

    values = [features[column] for column in FEATURE_COLUMNS]
    invalid = [
        column
        for column, value in zip(FEATURE_COLUMNS, values)
        if isinstance(value, bool) or not isinstance(value, Real)
    ]
    if invalid:
        raise ValueError(f"Feature values must be numeric: {', '.join(invalid)}")

    frame = pd.DataFrame([values], columns=FEATURE_COLUMNS, dtype=float)
    if not np.isfinite(frame.to_numpy()).all():
        raise ValueError("Feature values must be finite and must not be missing")
    return frame


def predict_bp_category(features: Mapping[str, Real]) -> BPCategoryPrediction:
    """Predict an experimental BP-associated category from one feature mapping."""
    if not isinstance(features, Mapping):
        raise TypeError("features must be a mapping of feature names to numeric values")

    input_frame = _features_to_frame(features)
    model = _load_model()
    predicted_class_id = int(model.predict(input_frame)[0])
    probabilities_array = np.asarray(model.predict_proba(input_frame)[0], dtype=float)

    if predicted_class_id not in _CATEGORY_BY_ID:
        raise ValueError(f"Model returned unknown class ID: {predicted_class_id}")
    class_ids = np.asarray(model.classes_)
    if class_ids.shape != (len(LABEL_MAPPING),):
        raise ValueError("Model returned an unexpected number of classes")
    if any(int(class_id) not in _CATEGORY_BY_ID for class_id in class_ids):
        raise ValueError("Model returned an unknown class ID")
    if probabilities_array.shape != class_ids.shape:
        raise ValueError("Model returned an unexpected number of class probabilities")
    if not np.isfinite(probabilities_array).all():
        raise ValueError("Model returned non-finite class probabilities")

    probabilities = {
        _CATEGORY_BY_ID[int(class_id)]: float(probabilities_array[index])
        for index, class_id in enumerate(class_ids)
    }
    explanations = _local_feature_sensitivity(input_frame, model, predicted_class_id)
    return BPCategoryPrediction(
        predicted_class_id=predicted_class_id,
        predicted_category=_CATEGORY_BY_ID[predicted_class_id],
        probabilities=probabilities,
        explanations=explanations,
    )


_FEATURE_LABELS = {
    "age": "Age",
    "sex_female": "Sex encoding",
    "bmi": "BMI",
    "sodium_mg_mean": "Mean daily sodium",
    "potassium_mg_mean": "Mean daily potassium",
    "energy_kcal_mean": "Mean daily energy",
    "sat_fat_g_mean": "Mean daily saturated fat",
    "na_k_ratio_mean": "Sodium-to-potassium ratio",
}


def _reference_values() -> dict[str, float]:
    """Load medians from the selected model's development partition."""
    try:
        metadata = json.loads(METADATA_PATH.read_text(encoding="utf-8"))
        values = metadata.get("feature_reference_medians", {})
        if all(column in values and np.isfinite(float(values[column])) for column in FEATURE_COLUMNS):
            return {column: float(values[column]) for column in FEATURE_COLUMNS}
    except (OSError, ValueError, TypeError, json.JSONDecodeError):
        pass
    # Safe fallback for test doubles or incomplete metadata; real model metadata
    # generated by the training script includes the training-partition medians.
    return {
        "age": 70.0, "sex_female": 0.0, "bmi": 27.0,
        "sodium_mg_mean": 2300.0, "potassium_mg_mean": 3000.0,
        "energy_kcal_mean": 2000.0, "sat_fat_g_mean": 20.0,
        "na_k_ratio_mean": 0.77,
    }


def _local_feature_sensitivity(frame: pd.DataFrame, model, predicted_class_id: int) -> list[dict[str, object]]:
    """Approximate local model sensitivity by replacing one feature with its
    development-partition median. These are not causal explanations.
    """
    try:
        classes = [int(value) for value in model.classes_]
        target_index = classes.index(predicted_class_id)
        base_probability = float(model.predict_proba(frame)[0][target_index])
        references = _reference_values()
        rows = []
        for column in FEATURE_COLUMNS:
            altered = frame.copy()
            altered.loc[altered.index[0], column] = references[column]
            changed_probability = float(model.predict_proba(altered)[0][target_index])
            delta = base_probability - changed_probability
            rows.append({
                "feature": column,
                "label": _FEATURE_LABELS.get(column, column),
                "value": float(frame.iloc[0][column]),
                "reference_value": float(references[column]),
                "probability_delta": float(delta),
                "direction": "higher model score than reference" if delta > 1e-6
                             else "lower model score than reference" if delta < -1e-6
                             else "little change versus reference",
            })
        rows.sort(key=lambda item: abs(float(item["probability_delta"])), reverse=True)
        return rows[:3]
    except (AttributeError, IndexError, KeyError, TypeError, ValueError, ZeroDivisionError):
        return []
