CREATE TABLE IF NOT EXISTS public.component1_assessment_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_account_id TEXT NOT NULL,
    assessed_at TIMESTAMPTZ NOT NULL,
    inputs JSONB NOT NULL CHECK (jsonb_typeof(inputs) = 'object'),
    result JSONB NOT NULL CHECK (jsonb_typeof(result) = 'object'),
    legacy_sqlite_id INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_component1_assessment_history_account_date
    ON public.component1_assessment_history
    (local_account_id, assessed_at DESC, id DESC);

CREATE UNIQUE INDEX IF NOT EXISTS uq_component1_assessment_history_legacy
    ON public.component1_assessment_history
    (local_account_id, legacy_sqlite_id)
    WHERE legacy_sqlite_id IS NOT NULL;